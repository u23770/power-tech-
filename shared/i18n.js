const listeners = new Set();
let current = readStoredLang();

function readStoredLang() {
  try {
    return localStorage.getItem(STORAGE_KEY) === 'ar' ? 'ar' : 'en';
  } catch {
    return 'en'; // storage can be blocked (privacy mode); fall back to English
  }
}

export function getLang() {
  return current;
}

/** Translate a key. Falls back to English, then to the key itself (visible, so gaps are easy to spot). */
export function t(key, vars = {}) {
  const template = DICT[current][key] ?? DICT.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`));
}

/** Pick the language-specific field of a bilingual record: e.g. localized(p, 'title') -> p.title_ar or p.title_en. */
export function localized(record, base, lang = current) {
  const ar = record?.[`${base}_ar`];
  const en = record?.[`${base}_en`];
  return lang === 'ar' ? (ar || en || '') : (en || ar || '');
}

export function applyDocumentDirection(lang = current) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
}

/** Update every [data-i18n] text node and [data-i18n-attr="placeholder:key;aria-label:key"] attribute. */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-attr]').forEach((node) => {
    for (const pair of node.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':').map((s) => s.trim());
      if (attr && key) node.setAttribute(attr, t(key));
    }
  });
}

export function setLang(lang) {
  current = lang === 'ar' ? 'ar' : 'en';
  try {
    localStorage.setItem(STORAGE_KEY, current);
  } catch {
    /* storage unavailable: language still applies for this page view */
  }
  applyDocumentDirection(current);
  applyI18n(document);
  listeners.forEach((fn) => fn(current));
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

